  opencode: process.env.COWORKANY_MAC_OPENCODE_RUNTIME_DIR,
  python: process.env.COWORKANY_MAC_PYTHON_RUNTIME_DIR,
  font: process.env.COWORKANY_MAC_FONT_PATH,
